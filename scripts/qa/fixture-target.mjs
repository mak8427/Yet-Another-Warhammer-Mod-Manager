/**
 * Safety predicate for `generate-fixtures.mjs --scale`.
 *
 * `--scale` deletes its target before writing (`rm -r`), so the target must be
 * a disposable directory. This module owns the decision, separate from the
 * deletion itself, so the guard can be tested without touching a filesystem.
 *
 * A target is refused when it is:
 *   - the repository root, or any path inside the repository;
 *   - an ancestor of the repository;
 *   - the user's home directory, or an ancestor of it;
 *   - an existing non-empty directory that is not a previous `--scale` output,
 *     unless `force` is set.
 *
 * Symlinks are resolved before every comparison.
 */
import { readFileSync, readdirSync, realpathSync, statSync } from 'node:fs'
import { homedir } from 'node:os'
import * as nodePath from 'node:path'

export const SCALE_OUTPUT_SCHEMA = 'wh3mm.qa.scale-fixture.v1'
const SCALE_OUTPUT_MANIFEST = 'fixture-manifest.json'

/**
 * Absolute, symlink-free path for `target`, even when it does not exist yet:
 * resolve the deepest existing ancestor with realpath and re-append the
 * missing segments.
 */
export function canonicalPath(target) {
  const absolute = nodePath.resolve(target)
  let current = absolute
  const missing = []
  for (;;) {
    try {
      const resolved = realpathSync.native(current)
      return missing.length === 0 ? resolved : nodePath.join(resolved, ...missing.reverse())
    } catch (error) {
      if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') throw error
      const parent = nodePath.dirname(current)
      if (parent === current) return absolute
      missing.push(nodePath.basename(current))
      current = parent
    }
  }
}

function comparable(path) {
  return process.platform === 'win32' ? path.toLowerCase() : path
}

function samePath(left, right) {
  return comparable(left) === comparable(right)
}

/** True when `candidate` is strictly inside `parent`. */
export function isInside(parent, candidate) {
  const relative = nodePath.relative(comparable(parent), comparable(candidate))
  return (
    relative !== '' &&
    relative !== '..' &&
    !relative.startsWith(`..${nodePath.sep}`) &&
    !nodePath.isAbsolute(relative)
  )
}

function isSameOrAncestor(candidate, descendant) {
  return samePath(candidate, descendant) || isInside(candidate, descendant)
}

function isPreviousScaleOutput(directory) {
  try {
    const manifest = JSON.parse(readFileSync(nodePath.join(directory, SCALE_OUTPUT_MANIFEST), 'utf8'))
    return manifest?.schema === SCALE_OUTPUT_SCHEMA
  } catch {
    return false
  }
}

function refuse(path, reason) {
  return { ok: false, path, reason: `refusing --scale target ${JSON.stringify(path)}: it ${reason}` }
}

/**
 * Decides whether `target` may be deleted and regenerated by `--scale`.
 *
 * Returns `{ ok: true, path }` with the canonical target, or
 * `{ ok: false, path, reason }` with a user-facing explanation.
 */
export function checkScaleTarget(target, { repoRoot, home = homedir(), force = false } = {}) {
  if (!repoRoot) throw new TypeError('checkScaleTarget needs a repoRoot')
  const resolved = canonicalPath(target)
  const repo = canonicalPath(repoRoot)
  const homeDir = canonicalPath(home)

  if (samePath(resolved, repo)) return refuse(resolved, 'is the repository root')
  if (isInside(repo, resolved)) return refuse(resolved, 'is inside the repository')
  if (isSameOrAncestor(resolved, repo)) return refuse(resolved, 'is an ancestor of the repository')
  if (samePath(resolved, homeDir)) return refuse(resolved, 'is the user home directory')
  if (isSameOrAncestor(resolved, homeDir)) return refuse(resolved, 'is an ancestor of the user home directory')

  let stats
  try {
    stats = statSync(resolved)
  } catch (error) {
    if (error.code === 'ENOENT') return { ok: true, path: resolved }
    return refuse(resolved, `cannot be inspected (${error.code ?? error.message})`)
  }

  if (!stats.isDirectory()) return refuse(resolved, 'is not a directory')
  if (readdirSync(resolved).length === 0) return { ok: true, path: resolved }
  if (isPreviousScaleOutput(resolved)) return { ok: true, path: resolved }
  if (force) return { ok: true, path: resolved }
  return refuse(resolved, 'is not empty and is not a previous --scale output; pass --force to overwrite it')
}
