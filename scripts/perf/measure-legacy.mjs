const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function withTimeout(promise, ms, message) {
  let timer;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(message)), ms);
    }),
  ]).finally(() => clearTimeout(timer));
}

async function sha256File(path) {
  return createHash("sha256").update(await readFile(path)).digest("hex");
}

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? (sorted[mid - 1] + sorted[mid]) / 2 : sorted[mid];
}

/** Linear-interpolation quantile, the same definition R's type 7 uses. */
function quantile(values, fraction) {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return null;
  if (sorted.length === 1) return sorted[0];
  const position = (sorted.length - 1) * fraction;
  const lower = Math.floor(position);
  const upper = Math.ceil(position);
  if (lower === upper) return sorted[lower];
  return sorted[lower] + (sorted[upper] - sorted[lower]) * (position - lower);
}

function summarize(values) {
  if (values.length === 0) return null;
  const mean = values.reduce((sum, value) => sum + value, 0) / values.length;
  const variance = values.reduce((sum, value) => sum + (value - mean) ** 2, 0) / values.length;
  const stdev = Math.sqrt(variance);
  const p25 = quantile(values, 0.25);
  const p75 = quantile(values, 0.75);
  return {
    n: values.length,
    medianMs: Math.round(median(values)),
    meanMs: Math.round(mean),
    p25Ms: Math.round(p25),
    p75Ms: Math.round(p75),
    iqrMs: Math.round(p75 - p25),
    minMs: Math.round(Math.min(...values)),
    maxMs: Math.round(Math.max(...values)),
    stdevMs: Math.round(stdev),
    cvPercent: mean === 0 ? null : Number(((stdev / mean) * 100).toFixed(1)),
    samplesMs: values.map((value) => Math.round(value)),
  };
}

/** Minimal CDP client: Node 22 has a global WebSocket, so no dependency is needed. */
async function connectCDP(port, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(`http://127.0.0.1:${port}/json`);
      const targets = await response.json();
      const page = targets.find((target) => target.type === "page" && target.webSocketDebuggerUrl);
      if (page) return new CdpClient(page.webSocketDebuggerUrl);
    } catch {
      // The debugger endpoint is not up yet.
    }
    await sleep(150);
  }
  throw new Error(`CDP endpoint did not appear on port ${port}`);
}

class CdpClient {
  constructor(url) {
    this.url = url;
    this.nextId = 1;
    this.pending = new Map();
    this.listeners = new Map();
  }

  async open() {
    this.socket = new WebSocket(this.url);
    await new Promise((resolve, reject) => {
      this.socket.addEventListener("open", resolve, { once: true });
      this.socket.addEventListener("error", reject, { once: true });
    });
    this.socket.addEventListener("message", (event) => {
      const message = JSON.parse(event.data);
      if (!message.id) {
        for (const listener of this.listeners.get(message.method) ?? []) listener(message.params);
        return;
      }
      const pending = this.pending.get(message.id);
      if (!pending) return;
      this.pending.delete(message.id);
      if (message.error) pending.reject(new Error(JSON.stringify(message.error)));
      else pending.resolve(message.result);
    });
    this.socket.addEventListener("close", () => {
      for (const pending of this.pending.values()) pending.reject(new Error("CDP connection closed"));
      this.pending.clear();
    });
    return this;
  }

  send(method, params = {}) {
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject });
      this.socket.send(JSON.stringify({ id, method, params }));
    });
  }

  on(method, listener) {
    const listeners = this.listeners.get(method) ?? [];
    listeners.push(listener);
    this.listeners.set(method, listeners);
  }

  async evaluate(expression, { awaitPromise = false, timeout = 30_000 } = {}) {
    const limit = Math.max(timeout, 5_000);
    const result = await withTimeout(
      this.send("Runtime.evaluate", {
        expression,
        awaitPromise,
        returnByValue: true,
        timeout,
      }),
      limit,
      `renderer evaluation timed out after ${limit}ms`,
    );
    if (result.exceptionDetails) {
      throw new Error(result.exceptionDetails.text ?? "renderer evaluation failed");
    }
    return result.result?.value;
  }

  close() {
    try {
      this.socket?.close();
    } catch {
      // ignore
    }
  }
}

function killTree(child) {
  if (!child || child.exitCode !== null) return;
  if (process.platform === "win32") {
    try {
      execFileSync("taskkill", ["/PID", String(child.pid), "/T", "/F"], { stdio: "ignore" });
    } catch {
      // already gone
    }
  } else {
    try {
      process.kill(-child.pid, "SIGKILL");
    } catch {
      child.kill("SIGKILL");
    }
  }
}

async function prepareUserData(fixture, runDirectory) {
  const userData = nodePath.join(runDirectory, "userdata");
  await mkdir(userData, { recursive: true });
  await copyFile(nodePath.join(fixture, "userdata", "config.json"), nodePath.join(userData, "config.json"));
  // Cold every run: the header cache is the parse-complete marker, and a warm cache would hide the work.
  for (const name of ["pack-headers-cache.bin", "main_window.json", "config_backup_v2.29.0.json"]) {
    await rm(nodePath.join(userData, name), { force: true });
  }
  return userData;
}

function captureEnvironment() {
  return {
    capturedAt: new Date().toISOString(),
    os: `${process.platform} ${process.arch}`,
    osRelease: process.platform === "win32" ? execFileSync("cmd", ["/c", "ver"], { encoding: "utf8" }).trim() : null,
    node: process.version,
    cpu: process.platform === "win32" ? process.env.PROCESSOR_IDENTIFIER ?? null : nodeOs.cpus()[0]?.model ?? null,
    cpuCores: nodeOs.cpus().length,
    totalMemoryGiB: Number((nodeOs.totalmem() / 1024 ** 3).toFixed(1)),
    freeMemoryGiB: Number((nodeOs.freemem() / 1024 ** 3).toFixed(1)),
    runnerName: process.env.RUNNER_NAME ?? null,
    runnerOs: process.env.ImageOS ?? process.env.RUNNER_OS ?? null,
    runnerImage: process.env.ImageVersion ?? process.env.RUNNER_IMAGE ?? null,
  };
}

/**
 * Reads the persisted config and the derived counters the report needs. Returns null while the file
 * is being replaced, so callers can retry.
 */
async function readConfigState(configPath) {
  try {
    const [info, text] = await Promise.all([stat(configPath), readFile(configPath, "utf8")]);
    const json = JSON.parse(text);
    const gameConfig = json.games?.[json.currentGame ?? "wh3"];
    const preset = gameConfig?.currentPreset;
    const enabledNames = (preset?.mods ?? []).filter((mod) => mod.isEnabled !== false).map((mod) => mod.name);
    return {
      mtimeMs: info.mtimeMs,
      size: info.size,
      text,
      currentPresetName: preset?.name ?? null,
      enabledCount: enabledNames.length,
      enabledNames,
      modCount: preset?.mods?.length ?? 0,
      loadOrders: (preset?.mods ?? []).map((mod) => mod.loadOrder ?? null),
    };
  } catch {
    return null;
  }
}

async function waitForConfigQuiet(configPath, quietMs = 400, timeoutMs = 5_000) {
  const deadline = Date.now() + timeoutMs;
  let previous = await readConfigState(configPath);
  let stableSince = Date.now();
  while (Date.now() < deadline) {
    await sleep(50);
    const current = await readConfigState(configPath);
    if (!current) continue;
    if (!previous || current.text !== previous.text) {
      previous = current;
      stableSince = Date.now();
      continue;
    }
    if (Date.now() - stableSince >= quietMs) return current;
  }
  return previous;
}

async function waitForConfigChange(configPath, previousText, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const current = await readConfigState(configPath);
    if (current && current.text !== previousText) return current;
    await sleep(10);
  }
  return null;
}

async function waitForRenderer(cdp, expression, predicate, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  let last;
  while (Date.now() < deadline) {
    last = await cdp.evaluate(expression);
    if (predicate(last)) return last;
    await sleep(25);
  }
  return last;
}

/** Sends a trusted mouse click through CDP, so framework event handlers see a normal user click. */
async function clickAtPoint(cdp, x, y) {
  await cdp.send("Input.dispatchMouseEvent", { type: "mouseMoved", x, y, button: "none", clickCount: 0 });
  await cdp.send("Input.dispatchMouseEvent", { type: "mousePressed", x, y, button: "left", clickCount: 1 });
  await cdp.send("Input.dispatchMouseEvent", { type: "mouseReleased", x, y, button: "left", clickCount: 1 });
}

/**
 * Load-order apply/persist: enter placement mode on the first enabled row, drop it at position 5,
 * then time the path from the click to the legacy app's own config.json write. v2.29.0 has no Apply
 * button; the debounced saveConfig write is the persist that follows a load-order change.
 */
async function measureLoadOrderPersist(cdp, configPath) {
  const before = await waitForConfigQuiet(configPath);
  if (!before) return { ok: false, error: "config.json is not readable before the load-order change" };

  const placement = await cdp.evaluate(`(() => {
    const pane = document.getElementById("enabledModsPaneScroll") || document.getElementById("mod-rows-scroll");
    if (!pane) {
      return {
        ok: false,
        error: "mod list pane not found",
        debug: {
          panes: ["enabledModsPaneScroll", "disabledModsPaneScroll", "mod-rows-scroll"].filter((id) => document.getElementById(id)),
          dualLists: !!document.getElementById("dualModLists"),
        },
      };
    }
    const icons = [...pane.querySelectorAll('[id^="load-order-icon-"]')];
    if (icons.length === 0) {
      return {
        ok: false,
        error: "no load-order control in the mod list pane",
        debug: { pane: pane.id, rows: pane.querySelectorAll("[id^='mod-enabled-']").length },
      };
    }
    icons[0].click();
    return { ok: true, controlId: icons[0].id, controls: icons.length, pane: pane.id };
  })()`);
  if (!placement?.ok) return { ok: false, error: placement?.error ?? "could not enter placement mode", debug: placement?.debug };

  const targetPosition = 5;
  const placeholders = await waitForRenderer(
    cdp,
    `(() => [...document.querySelectorAll('[id^="enabled-mod-placeholder-"]')].map((element) => element.id))()`,
    (ids) => Array.isArray(ids) && ids.includes(`enabled-mod-placeholder-${targetPosition}`),
    3_000,
  );
  if (!Array.isArray(placeholders) || !placeholders.includes(`enabled-mod-placeholder-${targetPosition}`)) {
    await cdp.evaluate(`(() => document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true })))()`);
    return { ok: false, error: "load-order placeholders did not render", placeholders };
  }

  const started = Date.now();
  const dropped = await cdp.evaluate(`(() => {
    const placeholder = document.getElementById("enabled-mod-placeholder-${targetPosition}");
    if (!placeholder) return { ok: false };
    placeholder.click();
    return { ok: true };
  })()`);
  if (!dropped?.ok) return { ok: false, error: "load-order placeholder click failed" };

  const after = await waitForConfigChange(configPath, before.text, INTERACTION_TIMEOUT_MS);
  if (!after) {
    await cdp.evaluate(`(() => document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true })))()`);
    return { ok: false, error: `config.json did not change within ${INTERACTION_TIMEOUT_MS}ms` };
  }

  const changedOrder = after.loadOrders.some((value, index) => value !== before.loadOrders[index]);
  return {
    ok: true,
    ms: Date.now() - started,
    targetPosition,
    controlId: placement.controlId,
    verified: changedOrder || after.text !== before.text,
    enabledBefore: before.enabledCount,
    enabledAfter: after.enabledCount,
    modsBefore: before.modCount,
    modsAfter: after.modCount,
  };
}

/** Dispatches a real key event through CDP; the renderer sees the same path as a user keypress. */
async function pressKey(cdp, key, code, virtualKeyCode) {
  const event = { key, code, windowsVirtualKeyCode: virtualKeyCode, nativeVirtualKeyCode: virtualKeyCode };
  await cdp.send("Input.dispatchKeyEvent", { type: "keyDown", ...event });
  await cdp.send("Input.dispatchKeyEvent", { type: "keyUp", ...event });
}

/** Focuses the preset combobox input and returns a DOM snapshot for diagnostics. */
async function focusPresetInput(cdp) {
  return cdp.evaluate(`(() => {
    const section = document.getElementById("presetSection");
    const input = document.querySelector("#createOrSelectPreset input");
    if (!input) {
      return {
        ok: false,
        error: "preset combobox input not found",
        html: section ? section.innerHTML.slice(0, 2000) : null,
      };
    }
    input.focus();
    const rect = input.getBoundingClientRect();
    return { ok: true, x: rect.left + rect.width / 2, y: rect.top + rect.height / 2, value: input.value };
  })()`);
}

/**
 * Preset (profile) switch: focus the react-select combobox, open it with the keyboard, filter to the
 * target preset, then time from the Enter keypress that commits the option to the legacy app's
 * config.json write. The menu work is done before the clock starts, so the sample is the switch and
 * its persist, not the dropdown animation. Keyboard navigation is used because a synthetic click at
 * the control's centre did not expand this react-select instance in CI.
 */
async function measurePresetSwitch(cdp, configPath, presetName) {
  const before = await waitForConfigQuiet(configPath);
  if (!before) return { ok: false, error: "config.json is not readable before the preset switch" };

  const focused = await focusPresetInput(cdp);
  if (!focused?.ok) return { ok: false, error: focused?.error ?? "could not focus the preset input", debug: focused };

  await pressKey(cdp, "ArrowDown", "ArrowDown", 40);
  const listbox = await waitForRenderer(
    cdp,
    `(() => {
      const menu = document.getElementById("createOrSelectPreset-listbox") || document.querySelector('[id$="-listbox"]');
      return {
        menu: !!menu,
        menuId: menu?.id ?? null,
        options: menu ? [...menu.querySelectorAll('[id*="-option-"]')].map((option) => option.textContent.trim()) : [],
        html: document.getElementById("presetSection")?.innerHTML.slice(0, 2000) ?? null,
      };
    })()`,
    (state) => state.menu,
    2_000,
  );
  if (!listbox?.menu) {
    return { ok: false, error: "preset menu did not open from the keyboard", debug: listbox };
  }

  await cdp.send("Input.insertText", { text: presetName });
  const filtered = await waitForRenderer(
    cdp,
    `(() => {
      const menu = document.getElementById("createOrSelectPreset-listbox") || document.querySelector('[id$="-listbox"]');
      return {
        menu: !!menu,
        menuId: menu?.id ?? null,
        options: menu ? [...menu.querySelectorAll('[id*="-option-"]')].map((option) => option.textContent.trim()) : [],
        selected: menu?.querySelector('[id*="-option-"][aria-selected="true"]')?.textContent?.trim() ?? null,
      };
    })()`,
    (state) => state.options.includes(presetName),
    2_000,
  );
  if (!Array.isArray(filtered?.options) || !filtered.options.includes(presetName)) {
    await pressKey(cdp, "Escape", "Escape", 27);
    return { ok: false, error: `preset option "${presetName}" not found`, options: filtered?.options ?? [], debug: filtered };
  }

  const started = Date.now();
  await pressKey(cdp, "Enter", "Enter", 13);

  const after = await waitForConfigChange(configPath, before.text, INTERACTION_TIMEOUT_MS);
  if (!after) {
    return { ok: false, error: `config.json did not change within ${INTERACTION_TIMEOUT_MS}ms` };
  }

  return {
    ok: true,
    ms: Date.now() - started,
    preset: presetName,
    selection: filtered.selected,
    enabledBefore: before.enabledCount,
    enabledAfter: after.enabledCount,
    modsBefore: before.modCount,
    modsAfter: after.modCount,
    currentPresetName: after.currentPresetName,
    verified: after.enabledCount !== before.enabledCount || after.text !== before.text,
  };
}

/**
 * Game-launch handoff, proxy only: invoke the renderer's Play button, then wait for the stub game
 * process to write its marker file. The stub is a compiled Windows executable installed as
 * Warhammer3.exe in the fixture's game folder; it records the argv it was started with and exits.
 *
 * The click is dispatched in the page (element.click()) rather than as a hit-tested mouse event:
 * the Play button can sit below the fold in the sidebar on a small CI desktop, and a pointer click
 * then lands on empty space. element.click() runs the same React onClick handler as a user click.
 *
 * The sample covers renderer click -> startGame IPC -> used_mods.txt write -> launch-plan
 * resolution -> process creation -> stub startup. It excludes Steam, the game engine and a real
 * TW:WH3 launch; CI has no game install.
 */
async function measureGameLaunchHandoff(cdp, markerPath) {
  const armed = await cdp.evaluate(`(() => {
    const button = document.getElementById("playGame");
    if (!button) return { ok: false, error: "playGame button not found" };
    button.scrollIntoView({ block: "center" });
    const rect = button.getBoundingClientRect();
    return {
      ok: !button.disabled,
      disabled: button.disabled,
      rect: { x: rect.x, y: rect.y, width: rect.width, height: rect.height },
      viewport: { width: window.innerWidth, height: window.innerHeight },
    };
  })()`);
  if (!armed?.ok) return { ok: false, error: armed?.error ?? "playGame button is disabled", debug: armed };

  await rm(markerPath, { force: true });
  const started = Date.now();
  const clicked = await cdp.evaluate(
    `(() => {
      const button = document.getElementById("playGame");
      if (!button) return false;
      button.click();
      return true;
    })()`,
  );
  if (!clicked) return { ok: false, error: "playGame click could not be dispatched", debug: armed };

  const deadline = Date.now() + Math.max(INTERACTION_TIMEOUT_MS, 30_000);
  while (Date.now() < deadline) {
    try {
      const argv = await readFile(markerPath, "utf8");
      return {
        ok: true,
        ms: Date.now() - started,
        marker: markerPath,
        argv,
        method: "stub-process-start",
        click: "dom-element-click",
        proxy: true,
        debug: armed,
      };
    } catch {
      await sleep(5);
    }
  }
  return {
    ok: false,
    proxy: true,
    error: `the stub game process did not start within ${Math.max(INTERACTION_TIMEOUT_MS, 30_000)}ms`,
    marker: markerPath,
    debug: armed,
  };
}

async function runOnce({ index, appPath, fixture, runDirectory }) {
  const userData = await prepareUserData(fixture, runDirectory);
  const cachePath = nodePath.join(userData, "pack-headers-cache.bin");
  const configPath = nodePath.join(userData, "config.json");
  const logPath = nodePath.join(runDirectory, `run-${index + 1}.log`);
  const markerPath = nodePath.join(runDirectory, `launch-marker-${index + 1}.txt`);
  const port = CDP_PORT + index;
  const environment = captureEnvironment();
  const startedAt = process.hrtime.bigint();
  const ms = () => Number(process.hrtime.bigint() - startedAt) / 1e6;

  const child = spawn(appPath, [`--remote-debugging-port=${port}`, `--user-data-dir=${userData}`, "-nogpu"], {
    cwd: nodePath.dirname(appPath),
    env: { ...process.env, ELECTRON_ENABLE_LOGGING: "0", WH3MM_STUB_MARKER: markerPath },
    stdio: ["ignore", "pipe", "pipe"],
    detached: process.platform !== "win32",
  });

  const lines = [];
  let buffer = "";
  const onData = (chunk) => {
    buffer += chunk.toString("utf8");
    let newline;
    while ((newline = buffer.indexOf("\n")) !== -1) {
      const line = buffer.slice(0, newline).replace(/\r$/, "");
      buffer = buffer.slice(newline + 1);
      lines.push({ atMs: Math.round(ms()), line });
    }
  };
  child.stdout.on("data", onData);
  child.stderr.on("data", onData);

  let exitInfo = null;
  child.on("exit", (code, signal) => {
    exitInfo = { code, signal, atMs: Math.round(ms()) };
  });

  const findLine = (pattern) => lines.find((entry) => pattern.test(entry.line));
  const startupValue = (label) => {
    const entry = findLine(new RegExp(`\\[startup\\] Main renderer ${label} after (\\d+)ms`));
    return entry ? Number(entry.line.match(/after (\d+)ms/)[1]) : null;
  };

  const result = {
    run: index + 1,
    environment,
    coldStartMs: null,
    domReadyMs: null,
    finishedLoadMs: null,
    modsEnumeratedMs: null,
    modListPopulatedMs: null,
    headerScanMs: null,
    modCount: null,
    cdpConnected: false,
    appVersion: null,
    loadOrderPersist: null,
    presetSwitch: null,
    gameLaunch: null,
    error: null,
  };

  try {
    const deadline = Date.now() + BOOT_TIMEOUT_MS;
    let cacheSeenAt = null;
    while (Date.now() < deadline) {
      if (cacheSeenAt === null) {
        try {
          await stat(cachePath);
          cacheSeenAt = ms();
        } catch {
          // not written yet
        }
      }
      result.coldStartMs = startupValue("React mounted");
      result.domReadyMs = startupValue("DOM ready");
      result.finishedLoadMs = startupValue("finished loading");
      const enumerated = findLine(/before subscription filter: (\d+)/);
      const populated = findLine(/after subscription filter: (\d+)/);
      if (enumerated) result.modsEnumeratedMs = enumerated.atMs;
      if (populated) {
        result.modListPopulatedMs = populated.atMs;
        result.modCount = Number(populated.line.match(/after subscription filter: (\d+)/)[1]);
      }
      if (result.modListPopulatedMs !== null && cacheSeenAt !== null) break;
      if (exitInfo) break;
      await sleep(20);
    }

    if (cacheSeenAt !== null && result.modsEnumeratedMs !== null) {
      result.headerScanMs = cacheSeenAt - result.modsEnumeratedMs;
    }

    const versionLine = findLine(/"version"|\bwh3mm \d|WH3MM v?\d/);
    result.appVersion = versionLine?.line.slice(0, 120) ?? null;

    if (!SKIP_CDP && result.modListPopulatedMs !== null && !exitInfo) {
      try {
        const cdp = await connectCDP(port, 15_000).then((client) => client.open());
        cdp.on("Runtime.consoleAPICalled", (params) => {
          const text = (params.args ?? []).map((arg) => arg.value ?? arg.description ?? "").join(" ");
          lines.push({ atMs: Math.round(ms()), line: `[renderer:${params.type}] ${text}` });
        });
        await cdp.send("Runtime.enable");
        const dom = await cdp.evaluate(`(() => ({
          root: !!document.getElementById("mod-rows-scroll") || !!document.getElementById("enabledModsPaneScroll"),
          rows: document.querySelectorAll("[id^='mod-enabled-']").length,
          title: document.title,
        }))()`);
        result.cdpConnected = true;
        result.domReady = dom;
        result.appVersion = dom?.title?.match(/\bv?(\d+\.\d+\.\d+)\b/)?.[1] ?? null;

        if (!SKIP_INTERACTIONS) {
          await sleep(SETTLE_MS);
          try {
            result.loadOrderPersist = await measureLoadOrderPersist(cdp, configPath);
          } catch (error) {
            result.loadOrderPersist = { ok: false, error: String(error.message ?? error) };
          }
          try {
            result.presetSwitch = await measurePresetSwitch(cdp, configPath, PRESET_SWITCH_NAME);
          } catch (error) {
            result.presetSwitch = { ok: false, error: String(error.message ?? error) };
          }
          if (GAME_STUB) {
            try {
              result.gameLaunch = await measureGameLaunchHandoff(cdp, markerPath);
            } catch (error) {
              result.gameLaunch = { ok: false, proxy: true, error: String(error.message ?? error) };
            }
          }
        }
        const finalTitle = await cdp.evaluate(`document.title`);
        result.domReady = { ...(result.domReady ?? {}), titleAfterSettle: finalTitle };
        result.appVersion = finalTitle?.match(/\bv?(\d+\.\d+\.\d+)\b/)?.[1] ?? result.appVersion;
        cdp.close();
      } catch (error) {
        result.cdpError = String(error.message ?? error);
      }
    }

    if (result.modListPopulatedMs === null) {
      result.error =
        exitInfo !== null
          ? `app exited before populating mods (code ${exitInfo.code})`
          : `no "after subscription filter" log within ${BOOT_TIMEOUT_MS}ms`;
    }
  } finally {
    if (exitInfo) result.appExit = exitInfo;
    killTree(child);
    await sleep(400);
    await writeFile(logPath, lines.map((entry) => `${entry.atMs.toString().padStart(8)} | ${entry.line}`).join("\n"));
  }

  result.logPath = logPath;
  return result;
}

async function main() {
  const outputDirectory = nodePath.dirname(OUT);
  await mkdir(outputDirectory, { recursive: true });
  const workDirectory = nodePath.join(outputDirectory, `.legacy-baseline-${Date.now()}`);
  await mkdir(workDirectory, { recursive: true });

  if (GAME_STUB) {
    if (process.platform !== "win32") {
      throw new Error("--game-stub is Windows-only: the game handoff proxy launches a Windows process");
    }
    await copyFile(GAME_STUB, nodePath.join(FIXTURE, GAME_STUB_NAME));
  }

  const fixtureManifestPath = nodePath.join(FIXTURE, "fixture-manifest.json");
  const fixtureManifest = JSON.parse(await readFile(fixtureManifestPath, "utf8"));
  const fixtureConfig = JSON.parse(await readFile(nodePath.join(FIXTURE, "userdata", "config.json"), "utf8"));
  const fixturePresets = fixtureConfig.games?.wh3?.presets ?? [];

  const environment = {
    ...captureEnvironment(),
    appPath: APP,
    appSha256: await sha256File(APP),
    fixturePath: FIXTURE,
    fixtureSha256: fixtureManifest.sha256,
    fixturePacks: fixtureManifest.packFiles,
    runs: RUNS,
    presetSwitchTarget: PRESET_SWITCH_NAME,
    presets: fixturePresets.map((preset) => ({ name: preset.name, entries: preset.mods.length })),
    gameStub: GAME_STUB
      ? {
          sourcePath: GAME_STUB,
          installedAs: nodePath.join(FIXTURE, GAME_STUB_NAME),
          sha256: await sha256File(GAME_STUB),
          proxy: true,
        }
      : null,
  };

  const runs = [];
  for (let index = 0; index < RUNS; index++) {
    const result = await runOnce({ index, appPath: APP, fixture: FIXTURE, runDirectory: workDirectory });
    console.log(
      `run ${index + 1}/${RUNS}: coldStart=${result.coldStartMs} modsPopulated=${result.modListPopulatedMs} ` +
        `headerScan=${result.headerScanMs} loadOrderPersist=${result.loadOrderPersist?.ms ?? "n/a"} ` +
        `presetSwitch=${result.presetSwitch?.ms ?? "n/a"} gameLaunch=${result.gameLaunch?.ms ?? "n/a"} ` +
        `mods=${result.modCount}` +
        `${result.error ? ` error=${result.error}` : ""}`,
    );
    runs.push(result);
    if (result.error) break;
  }

  const successful = runs.filter((run) => !run.error);
  const loadOrderSamples = successful
    .map((run) => (run.loadOrderPersist?.ok ? run.loadOrderPersist.ms : null))
    .filter((value) => value !== null);
  const presetSamples = successful
    .map((run) => (run.presetSwitch?.ok ? run.presetSwitch.ms : null))
    .filter((value) => value !== null);
  const gameLaunchSamples = successful
    .map((run) => (run.gameLaunch?.ok ? run.gameLaunch.ms : null))
    .filter((value) => value !== null);
  const metrics = {
    coldStartMs: summarize(successful.map((run) => run.coldStartMs).filter(Number.isFinite)),
    modListPopulatedMs: summarize(successful.map((run) => run.modListPopulatedMs).filter(Number.isFinite)),
    headerScanMs: summarize(successful.map((run) => run.headerScanMs).filter((value) => value !== null)),
    loadOrderPersistMs: summarize(loadOrderSamples),
    presetSwitchMs: summarize(presetSamples),
    gameLaunchHandoffMs: summarize(gameLaunchSamples),
    modCount: successful.map((run) => run.modCount),
  };

  const interactionSummary = {
    loadOrderPersist: {
      attempted: successful.length,
      measured: loadOrderSamples.length,
      verified: successful.filter((run) => run.loadOrderPersist?.verified).length,
      errors: successful.filter((run) => run.loadOrderPersist && !run.loadOrderPersist.ok).map((run) => run.loadOrderPersist.error),
    },
    presetSwitch: {
      attempted: successful.length,
      target: PRESET_SWITCH_NAME,
      measured: presetSamples.length,
      verified: successful.filter((run) => run.presetSwitch?.verified).length,
      errors: successful.filter((run) => run.presetSwitch && !run.presetSwitch.ok).map((run) => run.presetSwitch.error),
    },
    gameLaunch: {
      attempted: GAME_STUB ? successful.length : 0,
      measured: gameLaunchSamples.length,
      verified: successful.filter((run) => run.gameLaunch?.ok && run.gameLaunch?.argv).length,
      proxy: true,
      method: "stub-process-start",
      errors: successful.filter((run) => run.gameLaunch && !run.gameLaunch.ok).map((run) => run.gameLaunch.error),
    },
  };

  const report = {
    schema: "wh3mm.perf.legacy-baseline.v1",
    environment,
    metrics,
    interactionSummary,
    runs,
    rawLogDirectory: workDirectory,
    notes: [
      "coldStartMs is main's own [startup] React-mounted timer, measured from process launch.",
      "modListPopulatedMs is process launch to the after-subscription-filter log, when main sends modsPopulated.",
      "headerScanMs is the time to parse every mod's PFH5 header, marked by the pack-headers-cache.bin write.",
      "The legacy app waits up to 5000ms for Steam subscription ids; without Steam this fixed wait is included.",
      "loadOrderPersistMs is CDP click (drop a row at position 5) to the legacy app's own config.json write; v2.29.0 has no Apply button and persists through the debounced saveConfig.",
      "presetSwitchMs is the Enter keypress on the filtered preset option to the config.json write that persists the new enabled set.",
      "gameLaunchHandoffMs is a PROXY: DOM click on #playGame to the marker write of a compiled stub Warhammer3.exe. It covers the startGame IPC, used_mods.txt write, launch-plan resolution, process creation and stub startup. It excludes Steam, the game engine, and a real TW:WH3 launch; CI has no game install.",
    ],
  };
  await writeFile(OUT, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  console.log(`wrote ${OUT}`);
  if (successful.length === 0) process.exitCode = 1;
}

await main();
